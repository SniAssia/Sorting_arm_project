function result = seven_slot_fsm()
%SEVEN_SLOT_FSM Capacity-aware sorting protocol specification (no Stateflow).
% New Pi controller stores 0..3 per color, blocks FULL or uncalibrated slots,
% and persists PENDING before ARM. Only human confirmation increments count.
% This is logical state-machine documentation, not physical occupancy sensing.
root=fileparts(mfilename('fullpath'));
folder=fullfile(root,'outputs','fsm');
if ~exist(folder,'dir'),mkdir(folder);end
rows={ ...
 'READY','Color=UNKNOWN','REJECTED','No serial commands'; ...
 'READY','Color recognized, count=3','FULL','Reject request'; ...
 'READY','Color recognized, next slot uncalibrated','UNCALIBRATED','Reject request'; ...
 'READY','Valid color, configured free slot','SET_ROUTE','Select slot=count+1'; ...
 'SET_ROUTE','SET above+drop acknowledged','CHECK_ROUTE','Check modeled reachability'; ...
 'SET_ROUTE','SET failure/timeout','ERROR','Do not arm'; ...
 'CHECK_ROUTE','CHECK error/timeout','ERROR','Do not arm'; ...
 'CHECK_ROUTE','CHECK OK','CONFIRM','Wait for operator'; ...
 'CONFIRM','Operator declines','CANCELLED','Do not arm'; ...
 'CONFIRM','Operator approves','PENDING','Persist transaction before motion'; ...
 'PENDING','State persisted','RUNNING','Send ARM then RUN'; ...
 'RUNNING','Command completion','VERIFY_PLACEMENT','Ask operator to inspect physical drop'; ...
 'RUNNING','Timeout/error/interruption','PENDING_REVIEW','Keep count unchanged'; ...
 'VERIFY_PLACEMENT','Operator confirms correct placement','COMMITTED','Increment only chosen color count'; ...
 'VERIFY_PLACEMENT','Not confirmed','PENDING_REVIEW','Keep count unchanged'; ...
 'PENDING_REVIEW','Reconcile placed (after inspection)','COMMITTED','Increment count'; ...
 'PENDING_REVIEW','Reconcile not-placed (after inspection)','CANCELLED','Clear pending without increment'; ...
 'COMMITTED','Next object','READY','Preserve counts'; ...
 'CANCELLED','Next object','READY','Preserve counts'; ...
 'ERROR','After inspection and correction','READY','Only if no pending transaction'; ...
 'FULL','Physical bin emptied and manual reset','READY','Reset matching color counter'; ...
 'UNCALIBRATED','Measured slot entered + verified','READY','Recheck next slot' ...
};
transitions=cell2table(rows,'VariableNames',{'From','Trigger','To','Effect'});
writetable(transitions,fullfile(folder,'slot_tracker_transitions.csv'));
figureHandle=figure('Visible','off','Color','white','Position',[100 100 1600 950]);
G=digraph(transitions.From,transitions.To);
p=plot(G,'Layout','force','NodeFontSize',9,'MarkerSize',6,'ArrowSize',9);
p.LineWidth=1.25;
title({'Capacity-aware Raspberry Pi controller FSM', ...
    'Transition guards and actions: slot_tracker_transitions.csv'});
axis off;
exportgraphics(figureHandle,fullfile(folder,'slot_tracker_fsm.png'),'Resolution',180);
close(figureHandle);
result.transitions=transitions;
% Verify expected state-count invariant for 3 slots per color.
counts=zeros(1,3);
record=zeros(9,3);
n=0;
for c=1:3
    for slot=1:3
        assert(counts(c)<3);
        assert(counts(c)+1==slot);
        counts(c)=counts(c)+1; % Only on confirmed physical placement.
        n=n+1;
        record(n,:)=[c,slot,counts(c)];
    end
    assert(counts(c)==3);
end
result.testCounts=counts;
result.testTrace=array2table(record,'VariableNames',{'ColorId','Slot','ConfirmedCount'});
writetable(result.testTrace,fullfile(folder,'slot_capacity_logical_example.csv'));
fprintf('Slot FSM saved; abstract three-per-color capacity example passed.\n');
fprintf('NOTE: This does not simulate camera, physical collisions or occupancy sensing.\n');
end
