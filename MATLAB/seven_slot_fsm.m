function result = seven_slot_fsm()
%SEVEN_SLOT_FSM Capacity-aware sorting protocol specification (no Stateflow).
% Three bins share the original firmware routes. Occupancy is a software estimate.
root=fileparts(mfilename('fullpath'));
folder=fullfile(root,'outputs','fsm');
if ~exist(folder,'dir'),mkdir(folder);end
rows={ ...
 'READY','Object classified','COLOR_DETECTED','Read color'; ...
 'COLOR_DETECTED','UNKNOWN','READY','Skip object'; ...
 'COLOR_DETECTED','Supported color','CAPACITY_CHECK','Read bin count'; ...
 'CAPACITY_CHECK','Count = 3','FULL','Reject before serial'; ...
 'FULL','End request','READY','Keep counts'; ...
 'CAPACITY_CHECK','Count < 3','ROUTE_VALIDATION','Send CHECK COLOR'; ...
 'ROUTE_VALIDATION','Rejected or timeout','READY','End request before motion'; ...
 'ROUTE_VALIDATION','CHECK OK','CONFIRMATION','Request operator approval'; ...
 'CONFIRMATION','Declined','READY','Cancel without motion'; ...
 'CONFIRMATION','Approved','EXECUTION','Save pending before ARM and RUN COLOR'; ...
 'EXECUTION','Started then sequence complete','COMPLETION','Accept firmware completion'; ...
 'EXECUTION','Error, timeout or interruption','PENDING_REVIEW','Keep pending and counts'; ...
 'COMPLETION','Commit','COUNTER_UPDATE','Atomically increment color and clear pending'; ...
 'COMPLETION','Interrupted before commit','PENDING_REVIEW','Inspect before recovery'; ...
 'PENDING_REVIEW','Stopped, inspected, placed and confirmed','COUNTER_UPDATE','Increment pending color once'; ...
 'PENDING_REVIEW','Stopped, inspected, not placed and confirmed','READY','Clear pending without increment'; ...
 'COUNTER_UPDATE','Saved','READY','Release operation lock'; ...
 'READY','Idle, emptied and reset confirmed','MANUAL_RESET','Zero selected counts'; ...
 'MANUAL_RESET','Saved','READY','Release operation lock'; ...
};
transitions=cell2table(rows,'VariableNames',{'From','Trigger','To','Effect'});
writetable(transitions,fullfile(folder,'slot_tracker_transitions.csv'));
figureHandle=figure('Visible','off','Color','white','Position',[100 100 1600 950]);
G=digraph(transitions.From,transitions.To);
p=plot(G,'Layout','force','NodeFontSize',9,'MarkerSize',6,'ArrowSize',9);
p.LineWidth=1.25;
title({'Capacity-aware Raspberry Pi controller FSM', ...
    'Transition guards and actions: slot_tracker_transitions.csv'});
axis off;
exportgraphics(figureHandle,fullfile(folder,'slot_tracker_fsm.png'),'Resolution',180);
close(figureHandle);
result.transitions=transitions;
% Verify expected state-count invariant for three objects per bin.
counts=zeros(1,3);
record=zeros(9,3);
n=0;
for c=1:3
    for object=1:3
        assert(counts(c)<3);
        assert(counts(c)+1==object);
        counts(c)=counts(c)+1; % Example of a completed command sequence.
        n=n+1;
        record(n,:)=[c,object,counts(c)];
    end
    assert(counts(c)==3);
end
result.testCounts=counts;
result.testTrace=array2table(record,'VariableNames',{'ColorId','ObjectNumber','EstimatedCount'});
writetable(result.testTrace,fullfile(folder,'slot_capacity_logical_example.csv'));
fprintf('Bin capacity FSM saved; abstract three-per-color capacity example passed.\n');
fprintf('NOTE: This does not simulate camera, physical collisions or occupancy sensing.\n');
end
